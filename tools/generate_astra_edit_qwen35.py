def build_handle(module, tokenizer, watched, args):
    """An evalrx ``Model`` over *module* that batches and caches generation.

    The fix path asks for one answer at a time. On the first request in a given
    weight state the handle generates every prepared prompt in batches and
    serves the rest from memory. The weight state is identified by the sums of
    the *watched* tensors (the ones the edit touches), which also tells the
    handle whether it is producing the baseline, the edit or the control.
    """
    import torch
    from transformers import LogitsProcessor, LogitsProcessorList

    from evalrx.core.capability import Capability
    from evalrx.core.model import Model, Trace

    class PresencePenalty(LogitsProcessor):
        """Subtract *penalty* from every token already generated in this answer."""

        def __init__(self, penalty: float, prompt_len: int) -> None:
            self.penalty, self.prompt_len = float(penalty), int(prompt_len)

        def __call__(self, input_ids, scores):
            generated = input_ids[:, self.prompt_len:]
            if generated.shape[1] == 0:
                return scores
            seen = torch.zeros_like(scores, dtype=torch.bool)
            seen.scatter_(1, generated, True)
            return scores - self.penalty * seen

    device = next(module.parameters()).device
    eos = module.generation_config.eos_token_id
    eos_ids = set(eos if isinstance(eos, (list, tuple)) else [eos]) - {None}
    if tokenizer.eos_token_id is not None:
        eos_ids.add(tokenizer.eos_token_id)
    pad_id = (tokenizer.pad_token_id if tokenizer.pad_token_id is not None
              else (min(eos_ids) if eos_ids else 0))

    class Handle(Model):
        def __init__(self) -> None:
            self.capabilities = frozenset({Capability.GENERATE, Capability.LOGITS})
            self.modalities = frozenset({"text"})
            self._hf = (module, tokenizer)
            self.prompts: list[str] = []
            self.padding_ok = True
            self.states: list[tuple] = []                 # fingerprints, in order of appearance
            self.records: dict[str, dict[str, dict]] = {}  # arm -> prompt -> record
            self.max_new_tokens = int(args.max_new_tokens)

        @property
        def _loaded(self):
            return self._hf

        def forward(self, inputs, capture, spec=None) -> Trace:
            ids = tokenizer(getattr(inputs, "prompt", str(inputs)))["input_ids"]
            with torch.no_grad():
                logits = module(input_ids=torch.tensor([ids], device=device)).logits[0]
            return Trace(tokens=[str(i) for i in ids], token_ids=list(ids),
                         provided={Capability.LOGITS}, logits=logits)

        # -- weight state ------------------------------------------------
        def arm(self) -> str:
            state = tuple(float(p.detach().double().sum()) for p in watched)
            if state not in self.states:
                self.states.append(state)
            index = self.states.index(state)
            return ARMS[index] if index < len(ARMS) else f"state_{index}"

        # -- generation --------------------------------------------------
        def batches(self) -> "list[list[int]]":
            """Prompt indices per batch: any prompts when padding is exact, else equal lengths."""
            order = list(range(len(self.prompts)))
            if self.padding_ok:
                return [order[i:i + args.batch_size] for i in range(0, len(order), args.batch_size)]
            by_len: dict[int, list[int]] = {}
            for i in order:
                by_len.setdefault(len(tokenizer(self.prompts[i])["input_ids"]), []).append(i)
            return [group[i:i + args.batch_size] for group in by_len.values()
                    for i in range(0, len(group), args.batch_size)]

        def generate_batch(self, prompts: "list[str]", *, max_new_tokens: int, seed: int,
                           min_new_tokens: int = 0) -> "list[dict]":
            encoded = [tokenizer(p)["input_ids"] for p in prompts]
            width = max(len(e) for e in encoded)
            ids = torch.full((len(encoded), width), pad_id, dtype=torch.long)
            mask = torch.zeros((len(encoded), width), dtype=torch.long)
            for row, e in enumerate(encoded):                # left padding
                ids[row, width - len(e):] = torch.tensor(e)
                mask[row, width - len(e):] = 1
            kwargs = dict(max_new_tokens=max_new_tokens, pad_token_id=pad_id)
            if eos_ids:
                kwargs["eos_token_id"] = sorted(eos_ids)
            if min_new_tokens:
                kwargs["min_new_tokens"] = min_new_tokens
            if args.greedy:
                kwargs["do_sample"] = False
            else:
                kwargs.update(do_sample=True, temperature=args.temperature, top_p=args.top_p,
                              top_k=args.top_k)
            processors = LogitsProcessorList()
            if args.presence_penalty and not args.greedy:
                processors.append(PresencePenalty(args.presence_penalty, width))
            torch.manual_seed(seed)
            with torch.no_grad():
                out = module.generate(input_ids=ids.to(device), attention_mask=mask.to(device),
                                      logits_processor=processors, **kwargs)
            records = []
            for row in range(len(encoded)):
                new = out[row, width:].tolist()
                stop = next((i for i, t in enumerate(new) if t in eos_ids), None)
                tokens = new if stop is None else new[:stop]
                records.append({
                    "text": tokenizer.decode(tokens, skip_special_tokens=False),
                    "n_tokens": len(tokens), "stopped": stop is not None, "token_ids": tokens,
                })
            return records

        def fill(self, arm: str) -> None:
            self.records[arm] = {}
            batches = self.batches()
            started = time.time()
            for number, batch in enumerate(batches):
                # The same seed for the same batch in every arm: the arms differ
                # by their weights, not by the random numbers they draw.
                done = self.generate_batch([self.prompts[i] for i in batch],
                                           max_new_tokens=self.max_new_tokens,
                                           seed=args.seed + number)
                for i, record in zip(batch, done):
                    self.records[arm][self.prompts[i]] = record
                elapsed = time.time() - started
                print(f"  [{arm}] batch {number + 1}/{len(batches)} "
                      f"({sum(r['n_tokens'] for r in done):,} tokens, {elapsed:.0f}s elapsed)",
                      flush=True)

        def generate(self, inputs, **kwargs) -> str:
            prompt = getattr(inputs, "prompt", str(inputs))
            arm = self.arm()
            if arm not in self.records:
                self.fill(arm)
            if prompt not in self.records[arm]:
                record = self.generate_batch([prompt], max_new_tokens=self.max_new_tokens,
                                             seed=args.seed)[0]
                self.records[arm][prompt] = record
            return self.records[arm][prompt]["text"]

        # -- is left padding exact here? -----------------------------------
        def _padded(self, prompts: "list[str]"):
            encoded = [tokenizer(p)["input_ids"] for p in prompts]
            width = max(len(e) for e in encoded)
            ids = torch.full((len(encoded), width), pad_id, dtype=torch.long)
            mask = torch.zeros((len(encoded), width), dtype=torch.long)
            for row, e in enumerate(encoded):
                ids[row, width - len(e):] = torch.tensor(e)
                mask[row, width - len(e):] = 1
            return encoded, width, ids.to(device), mask.to(device)

        def _gap(self, prompts: "list[str]") -> "tuple[float, bool, int]":
            """Largest top-5 log-prob gap between each prompt alone and in one batch."""
            encoded, width, ids, mask = self._padded(prompts)
            with torch.no_grad():
                batched = module(input_ids=ids, attention_mask=mask).logits[:, -1].float()
                worst, same_top = 0.0, True
                for row, e in enumerate(encoded):
                    alone = module(input_ids=torch.tensor([e], device=device)).logits[0, -1].float()
                    a = torch.log_softmax(alone, -1)
                    b = torch.log_softmax(batched[row], -1)
                    top = torch.topk(a, 5).indices
                    worst = max(worst, float((a[top] - b[top]).abs().max()))
                    same_top = same_top and int(a.argmax()) == int(b.argmax())
            return worst, same_top, sum(len(e) < width for e in encoded)

        def check_padding(self, prompts: "list[str]") -> dict:
            """Is a left-padded batch the same computation as each prompt alone?

            Measured in float32. In the checkpoint's own 16-bit dtype, running a
            prompt alone and in a batch already differs by rounding, which can
            both hide a masking error and look like one. Three gaps are reported:

            ``float32_padded``    prompts of different lengths, padded — the test;
            ``float32_unpadded``  one prompt repeated — the floor for float32;
            ``native_unpadded``   the same in the checkpoint's dtype — how much
                                  batching alone moves the output there.
            """
            dtype = next(module.parameters()).dtype
            before = [float(p.detach().double().sum()) for p in watched]
            native_floor, _, _ = self._gap([prompts[0]] * len(prompts))
            native_padded, native_top, n_padded = self._gap(prompts)
            module.float()
            try:
                f32_floor, _, _ = self._gap([prompts[0]] * len(prompts))
                f32_padded, f32_top, _ = self._gap(prompts)
            finally:
                module.to(dtype)
            after = [float(p.detach().double().sum()) for p in watched]
            if before != after:  # a 16-bit value survives the trip through float32 exactly
                raise RuntimeError("the weights changed during the padding check")
            ok = f32_top and f32_padded < max(args.padding_tolerance, 10 * f32_floor)
            return {"ok": bool(ok), "n_prompts": len(prompts), "n_padded": n_padded,
                    "float32_padded": f32_padded, "float32_unpadded": f32_floor,
                    "float32_same_top1": bool(f32_top), "native_padded": native_padded,
                    "native_unpadded": native_floor, "native_same_top1": bool(native_top),
                    "native_dtype": str(dtype).replace("torch.", "")}

    return Handle()


