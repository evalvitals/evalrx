"""Generation-level check of a published weight edit through the L4 fix path.

The teacher-forced audits say what the edit does to the probability of text
the unedited model wrote. This script lets the models write: GSM8K problems are
generated by the unedited Qwen3.5-0.8B, by the model with the p50c edit of
"Sparks of Weight-Space Programming" written in, and by the model with a
matched random-direction control written in. The comparison runs through
evalrx's own repair path:

    FixAgent(weight_edit={"edit_dir": ...})  ->  rank_one_weight_edit candidate
      baseline generation, edit generation, control generation
      paired McNemar + e-value on correct / incorrect

and, per arm, reports whether the model left its thinking block, whether it
stopped on its own, whether it ended in a loop, and accuracy.

Protocol. As in the original evaluation: chat template with thinking ON, user
turn = problem + newline + "Please reason step by step, and put your final
answer within \\boxed{}.", sampling at temperature 0.6, top_p 0.95, top_k 20,
presence penalty 1.5. Differences from the original, which matter:

* Token budget. The original allowed 32,768 new tokens per answer; the
  unedited model used 29,289 on average and the edited one 11,993. This script
  defaults to 16,384. An answer that needs more counts as unfinished here, so
  absolute accuracies are below the published ones for both arms.
* Engine. Hugging Face ``generate`` instead of vLLM, one sample per problem
  instead of two, and the presence penalty implemented here (on generated
  tokens only).
* Grading. Numeric comparison of the last boxed answer after the thinking
  block with the gold number, not math-verify.

Speed. Answers are generated in batches, cached per weight state, and handed to
the fix path one by one. Batching pads prompts on the left; before any long
generation the script checks that a padded batch reproduces unpadded results on
this architecture. The check runs in float32, because in the checkpoint's 16-bit
dtype batching alone already moves the output by rounding. If padding is not
exact, problems are chosen so that every batch holds prompts of equal length. Run with ``--timing-only`` first: it performs that check, measures
tokens per second, prints a time estimate and exits.

    python tools/generate_astra_edit_qwen35.py --edit-lens ~/Github/edit-lens --timing-only
    python tools/generate_astra_edit_qwen35.py --edit-lens ~/Github/edit-lens
"""

