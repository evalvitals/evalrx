def answer_text(text: str) -> str:
    """The part of a response the answer is read from: after the last ``</think>``."""
    return text.split("</think>")[-1].strip() if "</think>" in text else text


def last_boxed(text: str) -> "str | None":
    """Content of the last ``\\boxed{...}`` (brace matched), or ``None``."""
    start = text.rfind("\\boxed")
    if start < 0:
        return None
    open_at = text.find("{", start)
    if open_at < 0 or text[start + len("\\boxed"):open_at].strip():
        return None
    depth = 0
    for i in range(open_at, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_at + 1:i]
    return None


def to_number(value: "str | None") -> "float | None":
    """A boxed answer as a number, or ``None`` when it is not one."""
    if value is None:
        return None
    s = value.strip()
    s = re.sub(r"\\text\{[^}]*\}|\\mathrm\{[^}]*\}", "", s)
    s = s.replace("\\$", "").replace("$", "").replace("\\%", "").replace("%", "")
    s = s.replace("\\!", "").replace("\\,", "").replace(",", "").replace(" ", "")
    frac = re.fullmatch(r"\\d?frac\{(-?[\d.]+)\}\{(-?[\d.]+)\}", s)
    try:
        if frac:
            return float(frac.group(1)) / float(frac.group(2))
        if re.fullmatch(r"-?[\d.]+/-?[\d.]+", s):
            a, b = s.split("/")
            return float(a) / float(b)
        match = re.match(r"-?\d+(?:\.\d+)?", s)
        return float(match.group(0)) if match and match.end() == len(s) else None
    except (ValueError, ZeroDivisionError):
        return None


def is_correct(text: str, gold: str) -> bool:
    pred, target = to_number(last_boxed(answer_text(text))), to_number(gold)
    return pred is not None and target is not None and abs(pred - target) < 1e-6


def verbatim_loop_end(text: str, max_period: int = 200, min_repeats: int = 3,
                      min_span: int = 40) -> bool:
    """Whether the text ends with one block of words repeated back to back.

    The last word is dropped (a response cut at the cap usually stops inside
    one). A block of 1..max_period words must repeat at least *min_repeats*
    times and cover at least *min_span* words.
    """
    words = text.split()[:-1]
    n = len(words)
    for period in range(1, max_period + 1):
        reps = max(min_repeats, -(-min_span // period))
        if reps * period > n:
            break
        block = words[n - period:]
        if all(words[n - (j + 1) * period:n - j * period] == block for j in range(1, reps)):
            return True
    return False


