def gsm8k_cases(edit_lens: str, tokenizer, n_cases: int, stride: int, *,
                equal_length_batches: int = 0):
    """GSM8K test problems as cases.

    Default: every *stride*-th problem. With ``equal_length_batches=B``:
    problems are instead taken from the prompt lengths (in tokens) shared by at
    least B problems, B per length, so every batch can be formed without
    padding. That narrows the sample to common prompt lengths; the lengths used
    are printed.
    """
    from evalrx.core.case import CaseBatch, FailureCase, Inputs

    rows = []
    with open(os.path.join(edit_lens, "data", "gsm8k_test.jsonl"), encoding="utf-8") as fh:
        for line in fh:
            rows.append(json.loads(line))

    def prompt_of(row: dict) -> str:
        return tokenizer.apply_chat_template(
            [{"role": "user", "content": row["question"] + "\n" + INSTRUCTION}],
            tokenize=False, add_generation_prompt=True, enable_thinking=True)

    if equal_length_batches:
        by_len: dict[int, list[dict]] = {}
        for row in rows:
            by_len.setdefault(len(tokenizer(prompt_of(row))["input_ids"]), []).append(row)
        full = sorted((n for n, group in by_len.items() if len(group) >= equal_length_batches),
                      key=lambda n: (-len(by_len[n]), n))
        needed = -(-n_cases // equal_length_batches)
        if len(full) < needed:
            raise SystemExit(
                f"only {len(full)} prompt lengths have {equal_length_batches} problems; "
                f"{needed} are needed. Lower --batch-size or --n-cases.")
        used = sorted(full[:needed])
        chosen = [row for n in used for row in by_len[n][:equal_length_batches]][:n_cases]
        print(f"problems chosen by prompt length so that batches need no padding: "
              f"lengths {used} tokens, {equal_length_batches} problems each")
    else:
        chosen = rows[::max(1, stride)][:n_cases]
    cases = []
    for row in chosen:
        gold = row["answer"].split("####")[-1].strip().replace(",", "")
        cases.append(FailureCase(inputs=Inputs(prompt=prompt_of(row)), expected=gold,
                                 id=str(row["id"])))
    return CaseBatch(cases)


def arm_summary(records: "dict[str, dict]", cases, max_new_tokens: int, ngram: int) -> dict:
    from evalrx.wsp import repetition_mask

    rows = []
    for case in cases:
        record = records.get(case.inputs.prompt)
        if record is None:
            continue
        mask = repetition_mask(record["token_ids"], ngram)
        rows.append({
            "id": case.id, "correct": is_correct(record["text"], str(case.expected)),
            "left_thinking": "</think>" in record["text"], "stopped": record["stopped"],
            "boxed": last_boxed(answer_text(record["text"])) is not None,
            "n_tokens": record["n_tokens"], "hit_cap": record["n_tokens"] >= max_new_tokens,
            "verbatim_loop_end": verbatim_loop_end(record["text"]),
            "loop_share": sum(mask) / len(mask) if mask else 0.0,
        })
    n = len(rows)
    if not n:
        return {"n": 0, "rows": []}

    def share(key: str) -> float:
        return sum(bool(r[key]) for r in rows) / n

    return {"n": n, "accuracy": share("correct"), "left_thinking": share("left_thinking"),
            "stopped_on_its_own": share("stopped"), "boxed_answer": share("boxed"),
            "hit_token_cap": share("hit_cap"), "verbatim_loop_end": share("verbatim_loop_end"),
            "mean_new_tokens": sum(r["n_tokens"] for r in rows) / n,
            "mean_loop_share": sum(r["loop_share"] for r in rows) / n, "rows": rows}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--edit-lens", required=True, help="path to a clone of edit-lens")
    parser.add_argument("--edit-dir", default="")
    parser.add_argument("--model", default=base.BASE_REPO)
    parser.add_argument("--revision", default=base.BASE_REVISION)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--n-cases", type=int, default=64)
    parser.add_argument("--stride", type=int, default=20,
                        help="take every stride-th GSM8K test problem")
    parser.add_argument("--max-new-tokens", type=int, default=16384)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--temperature", type=float, default=0.6)
    parser.add_argument("--top-p", type=float, default=0.95)
    parser.add_argument("--top-k", type=int, default=20)
    parser.add_argument("--presence-penalty", type=float, default=1.5)
    parser.add_argument("--greedy", action="store_true",
                        help="greedy decoding instead of the original sampling settings")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--no-control", action="store_true",
                        help="skip the random-direction control arm (saves a third of the time)")
    parser.add_argument("--no-verify-base", action="store_true")
    parser.add_argument("--padding-tolerance", type=float, default=0.01,
                        help="largest float32 log-prob gap accepted between padded and unpadded runs")
    parser.add_argument("--exact-batches", action="store_true",
                        help="never pad: choose problems whose prompts have equal length")
    parser.add_argument("--repeat-ngram", type=int, default=32)
    parser.add_argument("--timing-only", action="store_true",
                        help="check batching, measure speed, print a time estimate and exit")
    parser.add_argument("--out", default="astra_edit_generation.json")
    parser.add_argument("--save-texts", default="",
                        help="also write every generated answer to this .jsonl file")
    args = parser.parse_args()

    from evalrx.eval_agent.hypothesis import Hypothesis
    from evalrx.eval_agent.stages.fix.agent import FixAgent
    from evalrx.wsp import WeightEdit, applied, resolve_parameters

    edit_dir = args.edit_dir or os.path.join(args.edit_lens, "astra_logs", "exp8_math", "runs",
                                             "p50c", "edit")
    edit = WeightEdit.from_astra(edit_dir)
    module, tokenizer = base.load_model(args.model, args.revision or None, args.device)
    print(f"loaded {args.model} as {type(module).__name__} on {args.device}")
    if not args.no_verify_base:
        try:
            with applied(module, edit, verify_base=True):
                print("base hashes match")
        except (ValueError, KeyError) as exc:
            print(f"REFUSED: {exc}")
            return 1
    watched = [param for _, param in resolve_parameters(module, edit)]
    model = build_handle(module, tokenizer, watched, args)
    cases = gsm8k_cases(args.edit_lens, tokenizer, args.n_cases, args.stride)
    model.prompts = [c.inputs.prompt for c in cases]
    print(f"{len(cases)} GSM8K problems (every {args.stride}th), "
          f"up to {args.max_new_tokens:,} new tokens each, batch size {args.batch_size}, "
          + ("greedy" if args.greedy else
             f"sampling T={args.temperature} top_p={args.top_p} top_k={args.top_k} "
             f"presence_penalty={args.presence_penalty}"))

    # ---- Is left-padded batching exact on this architecture? -------------------------
    probe = sorted(model.prompts, key=len)
    probe = probe[:2] + probe[-2:] if len(probe) >= 4 else probe
    padding = model.check_padding(probe)
    print(f"padding check ({padding['n_prompts']} prompts, {padding['n_padded']} padded):")
    print(f"  float32: padded vs alone {padding['float32_padded']:.5f}, "
          f"same prompt repeated vs alone {padding['float32_unpadded']:.5f} "
          f"(largest top-5 log-prob gap; same top-1: {padding['float32_same_top1']})")
    print(f"  {padding['native_dtype']}: padded vs alone {padding['native_padded']:.5f}, "
          f"same prompt repeated vs alone {padding['native_unpadded']:.5f}")
    padding["exact"] = padding["ok"]
    if args.exact_batches:
        padding["ok"] = False
    if padding["ok"]:
        print("  -> padding is exact in float32; batching any prompts together. The "
              f"{padding['native_dtype']} gap is rounding, of the size batching alone causes.")
    else:
        print("  -> padding is not used ("
              + ("--exact-batches" if padding["exact"] else
                 "it changes the computation on this architecture")
              + "). Selecting problems whose prompts have equal length instead.")
        cases = gsm8k_cases(args.edit_lens, tokenizer, args.n_cases, args.stride,
                            equal_length_batches=args.batch_size)
        model.prompts = [c.inputs.prompt for c in cases]
    model.padding_ok = padding["ok"]
    batches = model.batches()
    print(f"{len(cases)} problems in {len(batches)} batches per arm "
          f"(sizes {sorted({len(b) for b in batches})})")

    # ---- Speed -----------------------------------------------------------------------
    first = batches[0]
    started = time.time()
    probe_tokens = 256
    model.generate_batch([model.prompts[i] for i in first], max_new_tokens=probe_tokens,
                         seed=args.seed, min_new_tokens=probe_tokens)
    seconds = time.time() - started
    rate = len(first) * probe_tokens / seconds
    arms = 2 if args.no_control else 3
    worst = arms * len(cases) * args.max_new_tokens / rate
    print(f"speed: {rate:,.0f} tokens/s on a batch of {len(first)} "
          f"({probe_tokens} tokens each, {seconds:.1f}s)")
    print(f"upper bound for {arms} arms if every answer ran to the cap at this speed: "
          f"{worst / 3600:.1f} h. Generation slows as answers get longer, and answers that "
          "stop early shorten it; treat this as a rough guide.")
    if args.timing_only:
        return 0

    # ---- The L4 fix path ---------------------------------------------------------------
    def score(case, output) -> bool:
        return is_correct(str(output), str(case.expected))

    agent = FixAgent(
        judge=None, max_tier="L4", allow_codegen=False, score_fn=score, floor_candidates=None,
        candidate_allowlist={"rank_one_weight_edit"},
        weight_edit={"edit_dir": edit_dir, "verify_base": not args.no_verify_base,
                     "control": not args.no_control, "seed": args.seed},
    )
    hypothesis = Hypothesis(
        statement="The model enters repetition loops while reasoning and never reaches an answer.",
        target_model=args.model, predicted_failure_mode="degenerate_repetition", test_design="")
    started = time.time()
    outcome = agent.propose_and_validate(model, cases, [hypothesis])
    print(f"fix path finished in {(time.time() - started) / 60:.1f} min")

    found = [v for v in outcome.attempted if v.candidate.kind == "weight_edit"]
    if not found:
        print("the weight-edit candidate was not attempted; candidates:",
              [(v.candidate.name, v.verdict) for v in outcome.attempted])
        return 1
    v = found[0]
    audit = v.candidate.payload.get("audit") or {}

    # ---- Report ------------------------------------------------------------------------
    summaries = {arm: arm_summary(model.records.get(arm, {}), cases, args.max_new_tokens,
                                  args.repeat_ngram) for arm in ARMS if arm in model.records}
    keys = [("accuracy", "accuracy"), ("left_thinking", "left the thinking block"),
            ("stopped_on_its_own", "stopped on its own"), ("boxed_answer", "gave a boxed answer"),
            ("hit_token_cap", "ran to the token cap"), ("verbatim_loop_end", "ended in a verbatim loop"),
            ("mean_loop_share", "mean share of loop tokens"), ("mean_new_tokens", "mean new tokens")]
    print(f"\n{'':<28}" + "".join(f"{arm:>12}" for arm in summaries))
    for key, label in keys:
        cells = []
        for arm in summaries:
            value = summaries[arm].get(key)
            cells.append("n/a" if value is None else
                         (f"{value:,.0f}" if key == "mean_new_tokens" else f"{value:.3f}"))
        print(f"{label:<28}" + "".join(f"{c:>12}" for c in cells))

    print("\npaired test, edit vs baseline (evalrx fix validation):")
    print(f"  verdict {v.verdict}; fixed {v.n_fixed}, broken {v.n_broken}, pairs {v.n_pairs}; "
          f"effect {v.effect}; e-value {v.e_value} (needs {v.e_threshold}); "
          f"execution error: {v.exec_error or 'none'}")
    print(f"  {v.summary}")
    print(f"  fix outcome: fixed={outcome.fixed}")
    if "control_random_direction" in audit:
        print(f"  correct answers: edit {audit.get('edit_result')}, "
              f"random-direction control {audit['control_random_direction']}")
    if "baseline" in summaries and "edit" in summaries:
        b = {r["id"]: r for r in summaries["baseline"]["rows"]}
        e = {r["id"]: r for r in summaries["edit"]["rows"]}
        shared = sorted(set(b) & set(e))
        left = sum(1 for i in shared if e[i]["left_thinking"] and not b[i]["left_thinking"])
        lost = sum(1 for i in shared if b[i]["left_thinking"] and not e[i]["left_thinking"])
        print(f"  left the thinking block only under the edit: {left}; only at baseline: {lost} "
              f"(of {len(shared)})")

    result = {
        "model": args.model, "revision": args.revision, "settings": vars(args),
        "padding_check": padding, "tokens_per_second_probe": rate,
        "arms": {arm: {k: s[k] for k in s if k != "rows"} for arm, s in summaries.items()},
        "per_case": {arm: s["rows"] for arm, s in summaries.items()},
        "validation": {"verdict": v.verdict, "n_fixed": v.n_fixed, "n_broken": v.n_broken,
                       "n_pairs": v.n_pairs, "effect": v.effect, "e_value": v.e_value,
                       "e_threshold": v.e_threshold, "summary": v.summary,
                       "exec_error": v.exec_error, "fixed_cases": v.fixed_cases,
                       "broken_cases": v.broken_cases, "outcome_fixed": bool(outcome.fixed)},
        "audit": audit,
    }
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=1, default=str)
    print(f"\nfull result written to {args.out}")
    if args.save_texts:
        with open(args.save_texts, "w", encoding="utf-8") as fh:
            for arm, records in model.records.items():
                for case in cases:
                    record = records.get(case.inputs.prompt)
                    if record is not None:
                        fh.write(json.dumps({"arm": arm, "id": case.id, "text": record["text"],
                                             "n_tokens": record["n_tokens"],
                                             "stopped": record["stopped"]}) + "\n")
        print(f"generated answers written to {args.save_texts}")
    return 0


