"""Text-LLM datasets: the nine band-located slices of examples/dataset_selection.

Nothing is vendored: ``datasets.py`` (the catalog: slice, grading rule, reference
accuracy) and ``band_locate.py`` (fetch through the HF datasets-server, row
adapters, ``extract_answer`` + per-dataset graders) are imported from
``examples/dataset_selection`` — one source of truth for what each slice is
and how it is graded. The manifest freezes the prompts + gold; Stage 0 is
generated by the runner like every other modality (serial hf_local calls,
thinking off, greedy), not by the endpoint path ``llm_benchmark`` uses.
"""

from __future__ import annotations

import importlib.util
import os
import sys
from functools import partial
from pathlib import Path
from typing import Any

from .base import Task, _protocol, write_manifest

DATASETS = (
    "cruxeval_output", "bbh_causal_judgement", "supergpqa_economics", "bbh_word_sorting",
    "bbh_tracking7", "bamboogle", "minervamath", "supergpqa_law", "supergpqa_medicine_hard",
)

PINNED_M1 = (
    "answer_extraction_audit",    # is the FAIL label real or a parse miss?
    "termination_audit",          # truncated / degenerate / gave up?
    "selfcheck_consistency",      # black-box hallucination signal
    "self_consistency",           # resample stability
    "calibration",                # stated/derived confidence vs correctness
    "logprob_entropy",            # answer-token uncertainty
    "coverage_verification_gap",  # cannot-solve vs cannot-select
    "perturbation_battery",       # invariance under paraphrase/no-op edits
)

_MODULE_NAME = "evalrx_llm_benchmark_datasets"


def dataset_selection_dir() -> Path:
    """``examples/dataset_selection`` — same relative place in the repo and in the images."""
    env = os.environ.get("EVALRX_DATASET_SELECTION_DIR")
    candidates = [Path(env)] if env else []
    candidates.append(Path(__file__).resolve().parents[3] / "dataset_selection")
    for cand in candidates:
        if (cand / "llm_benchmark" / "datasets.py").is_file() and (cand / "llm_band_probe" / "band_locate.py").is_file():
            return cand
    raise FileNotFoundError(
        "examples/dataset_selection (llm_benchmark/datasets.py + llm_band_probe/band_locate.py) "
        "not found; set EVALRX_DATASET_SELECTION_DIR"
    )


def catalog():
    """``(datasets_module, band_locate_module)`` loaded by path (never as ``datasets``,
    which would shadow the HuggingFace package)."""
    if _MODULE_NAME in sys.modules:
        mod = sys.modules[_MODULE_NAME]
        return mod, mod.B
    root = dataset_selection_dir()
    band = str(root / "llm_band_probe")
    if band not in sys.path:
        sys.path.insert(0, band)
    spec = importlib.util.spec_from_file_location(_MODULE_NAME, root / "llm_benchmark" / "datasets.py")
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules[_MODULE_NAME] = mod
    spec.loader.exec_module(mod)
    return mod, mod.B


def _entry(dataset: str):
    mod, B = catalog()
    return mod.get(dataset), B


def download(out_dir: Path, limit: int = 256, seed: int = 0, *, dataset: str,
             val_limit: int = 0) -> dict:
    """Freeze ``limit`` rows as manifest.json. ``val_limit`` > 0 keeps walking the
    SAME seeded draw past the main slice and freezes the next ``val_limit`` rows as
    manifest_val.json (disjoint held-out validation; empty when the slice is a
    census smaller than limit + val_limit, e.g. bbh_word_sorting's 250 items)."""
    entry, B = _entry(dataset)
    spec = entry.spec
    n = limit if limit and limit > 0 else entry.items
    val_limit = max(0, int(val_limit or 0))
    want = n + val_limit
    fetch = "datasets-server"
    try:
        rows = B.fetch_rows(spec, want, seed=seed)
    except RuntimeError as exc:
        # The /filter index behind a sliced spec can sit at HTTP 500 for hours;
        # the hub files are the same data, so freeze from them instead.
        print(f"[data] {exc}; freezing from the hub files instead (datasets.load_dataset)")
        rows = B.fetch_rows_hub(spec, want, seed=seed)
        fetch = "hub"
    adapter = spec.adapter or B._adapter_plain(spec.question_field, spec.answer_field)
    items = []
    for row in rows:
        pair = adapter(row)
        if pair:
            items.append(pair)
        if len(items) >= want:
            break
    if not items:
        raise SystemExit(f"{dataset}: adapter produced no gradable items")
    out = []
    for i, (question, gold) in enumerate(items):
        prompt = f"{question}\n\n{spec.instruction}" if spec.append_instruction else question
        golds = list(gold) if isinstance(gold, (list, tuple)) else [gold]
        out.append({
            "id": f"{dataset}-{i:04d}", "dataset": spec.dataset,
            "subset": f"{spec.config}/{spec.split}" + (f" where {spec.where}" if spec.where else ""),
            "sample_seed": seed, "image": None, "audio": None,
            "prompt": prompt, "answers": [str(g) for g in golds], "gold": gold,
            "task": "llm_graded", "numeric_tolerance": 0.0,
            "metadata": {"grading": entry.grading, "chapter": entry.chapter,
                         "reference_accuracy_qwen35_9b": entry.accuracy_9b},
        })
    out_dir = Path(out_dir)
    main_rows, val_rows = out[:n], out[n:n + val_limit]
    write_manifest(out_dir / "manifest.json", main_rows)
    summary = {"kept": len(main_rows), "slice_items": entry.items,
               "is_census": len(out) >= entry.items,
               "fetch": fetch, "manifest": str(out_dir / "manifest.json")}
    if val_limit:
        if val_rows:
            write_manifest(out_dir / "manifest_val.json", val_rows)
        else:
            print(f"[data] {dataset}: no rows left for a validation slice "
                  f"(slice has {len(out)} rows, main took {len(main_rows)})")
        summary.update(kept_val=len(val_rows), manifest_val=str(out_dir / "manifest_val.json"))
    return summary


def grade(dataset: str, output: str, gold: Any) -> bool:
    """The dataset's own grader on the extracted answer — the rule the labels use."""
    entry, B = _entry(dataset)
    spec = entry.spec
    text = str(output if output is not None else "")
    graded = text if getattr(spec, "grades_raw_output", False) else B.extract_answer(text)
    grader = spec.grader or B.answer_equal
    try:
        return bool(grader(graded, gold))
    except Exception:
        return False


def protocol(model_label: str, *, dataset: str):
    entry, _ = _entry(dataset)
    return _protocol(
        description=(
            f"A text-only LLM ({model_label}) answers items from {entry.source}. "
            f"{entry.slicing} Failure cases are items the model answered incorrectly; "
            "the batch also contains, as controls, items from the same slice it answered "
            "correctly. Each answer is scored against its own gold answer."
        ),
        task_domain=entry.chapter,
        success_criteria=entry.grading,
        failure_patterns="",
        target_modalities=frozenset({"text"}),
        metadata={"dataset": entry.name, "items_in_slice": entry.items,
                  "reference_accuracy_qwen35_9b": entry.accuracy_9b},
    )


TASKS = tuple(
    Task(
        name=name, modality="llm", kind="llm_graded", title=name,
        download=partial(download, dataset=name), protocol=partial(protocol, dataset=name),
        pinned_m1=PINNED_M1, default_limit=256, val_limit=128, default_seed=0, max_new_tokens=2048,
        short_answer=False, source="examples/dataset_selection/llm_benchmark/datasets.py",
    )
    for name in DATASETS
)
